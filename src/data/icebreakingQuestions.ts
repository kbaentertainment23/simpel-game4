// Helper to get randomized options for a question without leaking correctAnswerIndex
export function getRandomizedQuestion(raw: GameQuestion): GameQuestion {
  const shuffled = [...raw.options].sort(() => Math.random() - 0.5);
  return {
    id: raw.id,
    questionText: raw.questionText,
    options: shuffled,
    category: raw.category,
  };
}

export function pickRandomIcebreakingQuestion(excludeIds: string[] = []): GameQuestion {
  const pool = ICEBREAKING_QUESTIONS.filter((q) => !excludeIds.includes(q.id));
  const selected = pool.length > 0
    ? pool[Math.floor(Math.random() * pool.length)]
    : ICEBREAKING_QUESTIONS[Math.floor(Math.random() * ICEBREAKING_QUESTIONS.length)];

  return getRandomizedQuestion(selected);
}

// Dynamic question registry for questions loaded from Firestore packages
const dynamicQuestionRegistry = new Map<string, GameQuestion>();

export function registerDynamicQuestions(questions: GameQuestion[]): void {
  if (!Array.isArray(questions)) return;
  for (const q of questions) {
    if (q && q.id) {
      dynamicQuestionRegistry.set(q.id, q);
    }
  }
}

/**
 * Host-only helper: calculates the correct index on the teacher's screen only,
 * without having correctAnswerIndex stored in Firestore document.
 */
export function getCorrectAnswerIndexForTeacher(questionId?: string, currentOptions?: string[]): number {
  if (!questionId || !Array.isArray(currentOptions) || currentOptions.length === 0) return -1;
  const original = dynamicQuestionRegistry.get(questionId) || ICEBREAKING_QUESTIONS.find((q) => q.id === questionId);
  if (!original) return -1;
  const correctText = original.options[0];
  return currentOptions.indexOf(correctText);
}
